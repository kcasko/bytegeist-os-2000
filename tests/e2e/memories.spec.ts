import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('interactive fun fact connects through a TV loading screen and reveals Keith’s story', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Interactive fun fact', exact: true }).click()
  const memories = page.getByRole('dialog', { name: 'WebTV Memories', exact: true })
  await memories.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(memories.getByRole('progressbar', { name: 'WebTV connection progress' })).toBeVisible()
  await memories.getByRole('button', { name: 'Skip connection', exact: true }).click()
  await memories.getByRole('button', { name: 'Open my first homepage', exact: true }).click()
  await expect(memories.getByRole('heading', { name: 'I built my first websites on a television.', exact: true })).toBeVisible()
  await memories.getByRole('button', { name: 'Radioactive green', exact: true }).click()
  await expect(memories.getByRole('region', { name: 'My first homepage' })).toHaveAttribute('data-theme', 'green')
  await memories.getByRole('button', { name: 'Chat rooms', exact: true }).click()
  await expect(memories.getByText('CONNECTED TO: Talk City on WebTV', { exact: true })).toBeVisible()
  await memories.getByRole('button', { name: 'Next memory', exact: true }).click()
  await expect(memories.getByRole('heading', { name: 'The mIRC years.', exact: true })).toBeVisible()
  await memories.getByRole('button', { name: 'Today', exact: true }).click()
  await expect(memories.getByText(/At 46/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Enter Simulation', exact: true })).toHaveCount(0)
  await memories.getByRole('button', { name: 'Power off TV', exact: true }).click()
  await expect(memories.getByRole('button', { name: 'Connect', exact: true })).toBeVisible()
})

test('reduced motion skips the connection animation and the memory works on mobile', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Interactive fun fact', exact: true }).click()
  const memories = page.getByRole('dialog', { name: 'WebTV Memories', exact: true })
  await memories.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(memories.getByRole('button', { name: 'Open my first homepage', exact: true })).toBeVisible()
  await expect(memories.getByRole('progressbar')).toHaveCount(0)
  await memories.getByRole('button', { name: 'Open my first homepage', exact: true }).click()
  await expect(memories.getByRole('heading', { name: 'I built my first websites on a television.', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
})

test('TV connection finishes naturally and powering off cancels a pending connection', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: 'Interactive fun fact', exact: true }).click()
  const memories = page.getByRole('dialog', { name: 'WebTV Memories', exact: true })
  await memories.getByRole('button', { name: 'Connect', exact: true }).click()
  await page.clock.runFor(4000)
  await expect(memories.getByRole('button', { name: 'Open my first homepage', exact: true })).toBeVisible()
  await memories.getByRole('button', { name: 'Power off TV', exact: true }).click()
  await memories.getByRole('button', { name: 'Connect', exact: true }).click()
  await memories.getByRole('button', { name: 'Power off TV', exact: true }).click()
  await page.clock.runFor(6000)
  await expect(memories.getByRole('button', { name: 'Connect', exact: true })).toBeVisible()
  await expect(memories.getByRole('progressbar')).toHaveCount(0)
  await memories.getByRole('button', { name: 'Connect', exact: true }).click()
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('navigation', { name: 'Start menu' }).getByRole('button', { name: /My Projects/ }).click()
  const projects = page.getByRole('dialog', { name: 'My Projects', exact: true })
  await expect(projects).toBeFocused()
  await page.clock.runFor(4000)
  await expect(projects).toBeFocused()
})
