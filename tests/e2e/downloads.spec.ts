import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function queueSong(page: import('@playwright/test').Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open ByteWire' }).click()
  await page.getByRole('button', { name: 'Enter Simulation', exact: true }).click()
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await page.getByRole('button', { name: 'Select this-is-a-song.mp3', exact: true }).click()
  await page.getByRole('button', { name: 'Download selected (simulated)', exact: true }).click()
}

test('completed download opens through Downloads without inspecting Properties', async ({ page }) => {
  let actualDownloads = 0
  page.on('download', () => actualDownloads++)
  await queueSong(page)
  const client = page.getByRole('dialog', { name: 'ByteWire', exact: true })
  await expect(client.getByRole('progressbar', { name: 'Transfer progress: this-is-a-song.mp3', exact: true })).toBeVisible()
  await expect(client.getByRole('button', { name: 'Open file: this-is-a-song.mp3', exact: true })).toBeDisabled()
  await expect(client.getByRole('button', { name: 'Open file: this-is-a-song.mp3', exact: true })).toBeEnabled()
  await client.getByRole('button', { name: 'Open Downloads', exact: true }).click()
  const folder = page.getByRole('dialog', { name: 'Downloads', exact: true })
  await expect(folder.getByText('C:\\Downloads', { exact: true })).toBeVisible()
  await folder.getByRole('button', { name: 'Open this-is-a-song.mp3', exact: true }).click()
  await expect(folder.getByRole('heading', { name: 'Open File - Security Warning', exact: true })).toBeVisible()
  await expect(folder.getByText('this-is-a-song.mp3.exe', { exact: true })).toBeVisible()
  await expect(page.getByRole('complementary', { name: 'Fictional malware warning' })).toHaveCount(0)
  await folder.getByRole('button', { name: 'Run (simulated)', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Task Manager', exact: true })).toBeVisible()
  expect(actualDownloads).toBe(0)
})

test('transfers finish with ByteWire closed and can be cancelled and retried', async ({ page }) => {
  await queueSong(page)
  const client = page.getByRole('dialog', { name: 'ByteWire', exact: true })
  await client.getByRole('button', { name: 'Cancel transfer: this-is-a-song.mp3', exact: true }).click()
  await expect(client.getByText('No transfers yet. Nothing will be saved to your device.')).toBeVisible()
  await client.getByRole('button', { name: 'Download selected (simulated)', exact: true }).click()
  await page.getByRole('button', { name: 'Close ByteWire', exact: true }).click()
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('navigation', { name: 'Start menu' }).getByRole('button', { name: /Downloads/ }).click()
  await expect(page.getByRole('dialog', { name: 'Downloads', exact: true }).getByRole('button', { name: 'Open this-is-a-song.mp3', exact: true })).toBeEnabled()
})

test('folder actions work on mobile and filename extensions are optional evidence', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 840 })
  await queueSong(page)
  const client = page.getByRole('dialog', { name: 'ByteWire', exact: true })
  await expect(client.getByRole('button', { name: 'Open file: this-is-a-song.mp3', exact: true })).toBeEnabled()
  await client.getByRole('button', { name: 'Open Downloads', exact: true }).click()
  const folder = page.getByRole('dialog', { name: 'Downloads', exact: true })
  await folder.getByRole('checkbox', { name: 'Show filename extensions' }).check()
  await expect(folder.getByRole('button', { name: 'Select download: this-is-a-song.mp3.exe', exact: true })).toBeVisible()
  await folder.getByRole('button', { name: 'Open selected file', exact: true }).click()
  await folder.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Fictional malware warning' })).toHaveCount(0)
  await expect(folder.getByRole('button', { name: 'Open selected file', exact: true })).toBeFocused()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})

test('safe files open in simulated viewers without triggering infection', async ({ page }) => {
  await queueSong(page)
  const client = page.getByRole('dialog', { name: 'ByteWire', exact: true })
  await client.getByRole('button', { name: 'Select dial-up-daydream.mp3', exact: true }).click()
  await client.getByRole('button', { name: 'Download selected (simulated)', exact: true }).click()
  await expect(client.getByRole('button', { name: 'Open file: dial-up-daydream.mp3', exact: true })).toBeEnabled()
  await client.getByRole('button', { name: 'Open file: dial-up-daydream.mp3', exact: true }).click()
  await client.getByRole('button', { name: 'Play preview', exact: true }).click()
  await expect(client.getByText('PLAYING / DEMO TRACK', { exact: true })).toBeVisible()
  await client.getByRole('button', { name: 'Close preview', exact: true }).click()
  await client.getByRole('button', { name: 'Open file: dial-up-daydream.mp3', exact: true }).click()
  await expect(client.getByText('STOPPED / DEMO TRACK', { exact: true })).toBeVisible()
  await client.getByRole('button', { name: 'Close preview', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Fictional malware warning' })).toHaveCount(0)
  await client.getByRole('button', { name: 'Select bytewire-readme.txt', exact: true }).click()
  await client.getByRole('button', { name: 'Download selected (simulated)', exact: true }).click()
  await expect(client.getByRole('button', { name: 'Open file: bytewire-readme.txt', exact: true })).toBeEnabled()
  await client.getByRole('button', { name: 'Open file: bytewire-readme.txt', exact: true }).click()
  await expect(client.getByText(/Unknown publishers deserve a second look/)).toBeVisible()
})

test('blocking a file invalidates an already-open security warning', async ({ page }) => {
  await queueSong(page)
  const client = page.getByRole('dialog', { name: 'ByteWire', exact: true })
  await expect(client.getByRole('button', { name: 'Open file: this-is-a-song.mp3', exact: true })).toBeEnabled()
  await client.getByRole('button', { name: 'Open file: this-is-a-song.mp3', exact: true }).click()
  await client.getByRole('button', { name: 'Open Downloads', exact: true }).click()
  const folder = page.getByRole('dialog', { name: 'Downloads', exact: true })
  await folder.getByRole('button', { name: 'Properties', exact: true }).click()
  await folder.getByRole('button', { name: 'Flag as suspicious', exact: true }).click()
  await page.getByRole('button', { name: 'Task: ByteWire', exact: true }).click()
  await expect(client.getByRole('button', { name: 'Run (simulated)', exact: true })).toBeDisabled()
  await client.getByRole('button', { name: 'Try the infected route', exact: true }).click()
  await expect(client.getByRole('button', { name: 'Run (simulated)', exact: true })).toBeEnabled()
})

