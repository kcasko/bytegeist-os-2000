test('pointer resizing and icon dragging stay usable and Arrange Icons restores layout', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  const welcome = page.getByRole('dialog', { name: 'Welcome', exact: true })
  const original = (await welcome.boundingBox())!
  const handle = (await page.getByRole('button', { name: 'Resize Welcome', exact: true }).boundingBox())!
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x + handle.width / 2 + 70, handle.y + handle.height / 2 + 40, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => Math.round((await welcome.boundingBox())!.width)).toBe(Math.round(original.width + 70))
  await page.getByRole('button', { name: 'Close Welcome', exact: true }).click()
  const icon = page.getByRole('navigation', { name: 'Desktop applications' }).getByRole('button', { name: 'Welcome', exact: true })
  const before = (await icon.boundingBox())!
  await page.mouse.move(before.x + 30, before.y + 30)
  await page.mouse.down()
  await page.mouse.move(before.x + 130, before.y + 100, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => Math.round((await icon.boundingBox())!.x)).toBe(Math.round(before.x + 100))
  await page.getByRole('main').click({ button: 'right', position: { x: 1200, y: 650 } })
  await page.getByRole('menuitem', { name: 'Arrange Icons', exact: true }).click()
  await expect.poll(async () => Math.round((await icon.boundingBox())!.x)).toBe(Math.round(before.x))
})
