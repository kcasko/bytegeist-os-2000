import { test, expect } from '@playwright/test'

test('shortcuts select, double-click open and offer a context menu', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Close Welcome', exact: true }).click()
  const icon = page.getByRole('navigation', { name: 'Desktop applications' }).getByRole('button', { name: 'My Projects', exact: true })
  await icon.click()
  await expect(icon).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('dialog', { name: 'My Projects', exact: true })).toHaveCount(0)
  await icon.dblclick()
  await expect(page.getByRole('dialog', { name: 'My Projects', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close My Projects', exact: true }).click()
  await icon.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Open', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'My Projects', exact: true })).toBeVisible()
})

test('resizing, system menu, stable task order and Show Desktop work', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  const welcome = page.getByRole('dialog', { name: 'Welcome', exact: true })
  const before = (await welcome.boundingBox())!
  await page.getByRole('button', { name: 'Resize Welcome', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect.poll(async () => (await welcome.boundingBox())!.width).toBe(before.width + 16)
  await page.getByRole('button', { name: 'Window menu Welcome', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Maximize', exact: true }).click()
  await expect.poll(async () => (await welcome.boundingBox())!.width).toBe(1440)
  await page.getByRole('button', { name: 'Restore Welcome', exact: true }).click()
  await page.getByRole('button', { name: /Meet the operator/ }).click()
  await page.getByRole('button', { name: 'Task: Welcome', exact: true }).click()
  expect((await page.getByRole('button', { name: /^Task:/ }).allTextContents()).map(text => text.trim())).toEqual(['Welcome', 'About Keith'])
  await page.getByRole('button', { name: 'Show Desktop', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Show Desktop', exact: true }).click()
  await expect(welcome).toBeVisible()
})

test('Run launches Notepad and saved session notes reopen', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('navigation', { name: 'Start menu' }).getByRole('button', { name: 'Run…', exact: true }).click()
  const run = page.getByRole('dialog', { name: 'Run', exact: true })
  await run.getByRole('textbox', { name: 'Open:' }).fill('does-not-exist')
  await run.getByRole('button', { name: 'OK', exact: true }).click()
  await expect(run.getByRole('alert')).toContainText('Cannot find')
  await run.getByRole('textbox', { name: 'Open:' }).fill('notepad.exe')
  await run.getByRole('button', { name: 'OK', exact: true }).click()
  const note = page.getByRole('dialog', { name: 'Notepad', exact: true })
  await note.getByRole('textbox', { name: 'Notepad document' }).fill('Check startup before reboot.')
  await note.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('button', { name: 'Close Notepad', exact: true }).click()
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('navigation', { name: 'Start menu' }).getByRole('button', { name: 'Run…', exact: true }).click()
  await run.getByRole('button', { name: 'OK', exact: true }).click()
  await expect(note.getByRole('textbox', { name: 'Notepad document' })).toHaveValue('Check startup before reboot.')
})

