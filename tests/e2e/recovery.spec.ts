import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function infect(page: import('@playwright/test').Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open ByteWire' }).click()
  await page.getByRole('button', { name: 'Enter Simulation', exact: true }).click()
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await page.getByRole('button', { name: 'Select this-is-a-song.mp3', exact: true }).click()
  await page.getByRole('button', { name: 'Download selected (simulated)', exact: true }).click()
  await page.getByRole('button', { name: 'Properties: this-is-a-song.mp3', exact: true }).click()
  await page.getByRole('button', { name: 'Open file', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Fictional malware warning' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Run (simulated)', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Task Manager', exact: true })).toBeVisible()
}

for (const width of [320, 390, 768, 1440]) {
  test(`complete recovery and incident report at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 840 })
    await infect(page)
    if (width === 1440) expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
    const tasks = page.getByRole('dialog', { name: 'Task Manager', exact: true })
    await tasks.getByRole('button', { name: 'Inspect process', exact: true }).click()
    await tasks.getByRole('button', { name: 'End songhelper.exe', exact: true }).click()
    await expect(page.getByRole('complementary', { name: 'Fictional malware warning' })).toHaveCount(0)
    await tasks.getByRole('button', { name: 'Startup', exact: true }).click()
    const startup = page.getByRole('dialog', { name: 'Startup Manager', exact: true })
    await startup.getByRole('button', { name: 'Inspect startup entry', exact: true }).click()
    await startup.getByRole('button', { name: 'Disable ByteWire Helper', exact: true }).click()
    await startup.getByRole('button', { name: 'Scanner', exact: true }).click()
    const scanner = page.getByRole('dialog', { name: 'ByteDefender', exact: true })
    await scanner.getByRole('button', { name: 'Inspect suspicious file', exact: true }).click()
    await scanner.getByRole('button', { name: 'Quarantine executable', exact: true }).click()
    await scanner.getByRole('button', { name: 'Run verification scan', exact: true }).click()
    await expect(scanner.getByRole('button', { name: 'Run verification scan', exact: true })).toBeEnabled()
    await scanner.getByRole('button', { name: 'Simulate reboot', exact: true }).click()
    const report = page.getByRole('dialog', { name: 'Incident Report', exact: true })
    await expect(report.getByRole('heading', { name: 'I Survived ByteWire.' })).toBeVisible({ timeout: 8000 })
    await expect(report.getByText('RECOVERED / VERIFIED', { exact: true })).toBeVisible()
    await expect(report.getByText('Disguised executable: final extension .exe', { exact: true })).toBeVisible()
    if (width === 1440) expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
    await expect(page.getByRole('button', { name: 'Exit entire simulation', exact: true })).toBeInViewport()
    await page.getByRole('button', { name: 'Exit entire simulation', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Enter Simulation', exact: true })).toBeVisible()
    await expect(page.getByRole('complementary', { name: 'Simulation controls' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Close ByteWire', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Task: Welcome', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
  })
}

