test('infection escalates, survives dismissals, clears on containment and returns after unsafe reboot', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.clock.install()
  await infect(page)
  const symptoms = page.getByRole('complementary', { name: 'Fictional malware warning' })
  await expect(symptoms.getByRole('dialog')).toHaveCount(1)
  await page.clock.fastForward(4000)
  await page.clock.fastForward(4000)
  await expect(symptoms.getByRole('dialog')).toHaveCount(3)
  await page.getByRole('button', { name: 'Dismiss ByteGuard 2000 warning', exact: true }).click()
  await expect(symptoms.getByRole('dialog')).toHaveCount(2)
  await page.clock.fastForward(4000)
  await expect(symptoms.getByRole('dialog')).toHaveCount(3)
  await expect(page.getByRole('button', { name: 'Show infection activity', exact: true })).toBeVisible()
  const tasks = page.getByRole('dialog', { name: 'Task Manager', exact: true })
  await expect(tasks.getByText('SIMULATED CPU: 96%', { exact: true })).toBeVisible()
  await expect(tasks.getByRole('button', { name: 'End songhelper.exe', exact: true })).toBeInViewport()
  await tasks.getByRole('button', { name: 'End songhelper.exe', exact: true }).click()
  await expect(symptoms).toHaveCount(0)
  await expect(tasks.getByText('SIMULATED CPU: 3%', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Show infection activity', exact: true })).toHaveCount(0)
  await tasks.getByRole('button', { name: 'Scanner', exact: true }).click()
  await page.getByRole('dialog', { name: 'ByteDefender', exact: true }).getByRole('button', { name: 'Simulate reboot', exact: true }).click()
  await page.getByRole('button', { name: 'Skip startup', exact: true }).click()
  await expect(symptoms.getByRole('dialog')).toHaveCount(1)
  await page.getByRole('button', { name: 'Exit entire simulation', exact: true }).click()
  await page.clock.fastForward(60000)
  await expect(symptoms).toHaveCount(0)
})

