test('popup investigation reveals and focuses process details even when Task Manager is already open', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await infect(page)
  const tasks = page.getByRole('dialog', { name: 'Task Manager', exact: true })
  const popup = page.getByRole('complementary', { name: 'Fictional malware warning' }).getByRole('dialog').first()
  const investigate = popup.getByRole('button', { name: /Investigate process|Show process again/ })
  await investigate.click()
  await expect(popup.getByRole('button', { name: 'Show process again', exact: true })).toBeVisible()
  await expect(popup.getByRole('status')).toHaveText('Selected in Task Manager: songhelper.exe')
  const details = tasks.getByRole('region', { name: 'songhelper.exe process details' })
  await expect(details).toBeVisible()
  await expect(details).toBeFocused()
  await tasks.getByRole('button', { name: 'Inspect process', exact: true }).focus()
  await investigate.click()
  await expect(details).toBeFocused()
  await page.getByRole('button', { name: 'Minimize Task Manager', exact: true }).click()
  await investigate.click()
  await expect(details).toBeFocused()
  await page.getByRole('button', { name: 'Close Task Manager', exact: true }).click()
  await investigate.click()
  await expect(details).toBeFocused()
  await expect(tasks).toHaveCount(1)
})

