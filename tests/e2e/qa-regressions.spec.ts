test('desktop observes container growth without a browser resize event', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  const desktop = page.getByRole('main')
  const welcome = page.getByRole('dialog', { name: 'Welcome', exact: true })
  await expect(welcome).toBeVisible()
  await desktop.evaluate(el => { el.style.width = '390px' })
  await expect.poll(async () => (await welcome.boundingBox())!.width).toBe(390)
  await desktop.evaluate(el => { el.style.width = '1440px' })
  await expect.poll(async () => { const box = (await welcome.boundingBox())!; return { x: box.x, width: box.width, height: box.height } }).toEqual({ x: 180, width: 640, height: 540 })
  const icon = page.getByRole('navigation', { name: 'Desktop applications' }).getByRole('button', { name: 'My Projects', exact: true })
  await icon.dblclick()
  await expect(page.getByRole('dialog', { name: 'My Projects', exact: true })).toBeVisible()
})