test('Run focuses its input, rejects inherited property names and closes after launch', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('navigation', { name: 'Start menu' }).getByRole('button', { name: 'Run…', exact: true }).click()
  const run = page.getByRole('dialog', { name: 'Run', exact: true })
  await expect(run.getByRole('textbox', { name: 'Open:' })).toBeFocused()
  await run.getByRole('textbox', { name: 'Open:' }).fill('constructor')
  await run.getByRole('button', { name: 'OK', exact: true }).click()
  await expect(run.getByRole('alert')).toContainText('Cannot find')
  await run.getByRole('textbox', { name: 'Open:' }).fill('notepad')
  await run.getByRole('button', { name: 'OK', exact: true }).click()
  await expect(run).toHaveCount(0)
  const note = page.getByRole('dialog', { name: 'Notepad', exact: true })
  const text = note.getByRole('textbox', { name: 'Notepad document' })
  await expect(text).toBeFocused()
  await text.fill('Old saved note')
  await note.getByRole('button', { name: 'Save', exact: true }).click()
  await text.fill('New edited note')
  await note.getByRole('button', { name: 'Open saved', exact: true }).click()
  await page.getByRole('alertdialog', { name: 'Save changes to Notes.txt?' }).getByRole('button', { name: 'Save', exact: true }).click()
  await expect(text).toHaveValue('New edited note')
})

