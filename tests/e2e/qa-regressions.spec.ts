test('whole result rows select and a human-paced Cancel does not turn into Properties', async ({ page }) => {
  await page.clock.install()
  const wire = await client(page)
  await wire.getByRole('cell', { name: 'modem_poet', exact: true }).click()
  await expect(wire.getByRole('button', { name: 'Select dial-up-daydream.mp3', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(wire.getByRole('status')).toContainText('Selected dial-up-daydream.mp3')
  await wire.getByRole('button', { name: 'Download selected (simulated)', exact: true }).click()
  const cancel = wire.getByRole('button', { name: 'Cancel transfer: dial-up-daydream.mp3', exact: true })
  await expect(cancel).toBeInViewport()
  await page.clock.runFor(2000)
  await expect(cancel).toBeEnabled()
  await cancel.click()
  await expect(wire.getByText('No transfers yet. Nothing will be saved to your device.')).toBeVisible()
  await wire.getByRole('button', { name: 'Download selected (simulated)', exact: true }).click()
  await page.clock.runFor(5000)
  await expect(cancel).toBeDisabled()
  await expect(wire.getByRole('button', { name: 'Properties: dial-up-daydream.mp3', exact: true })).toBeEnabled()
  await wire.getByRole('button', { name: 'Download selected (simulated)', exact: true }).click()
  await expect(wire.getByRole('status')).toContainText('Already downloaded')
})

