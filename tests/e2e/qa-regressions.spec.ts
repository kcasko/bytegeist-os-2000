import { expect, test } from '@playwright/test'

async function client(page: import('@playwright/test').Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open ByteWire' }).click()
  await page.getByRole('button', { name: 'Enter Simulation', exact: true }).click()
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  return page.getByRole('dialog', { name: 'ByteWire', exact: true })
}
async function infect(page: import('@playwright/test').Page) {
  const wire = await client(page)
  await wire.getByRole('button', { name: 'Select this-is-a-song.mp3', exact: true }).click()
  await wire.getByRole('button', { name: 'Download selected (simulated)', exact: true }).click()
  await wire.getByRole('button', { name: 'Open file: this-is-a-song.mp3', exact: true }).click()
  await wire.getByRole('button', { name: 'Run (simulated)', exact: true }).click()
}

test('tiny startup recovers its intended size and phone rotation keeps window in bounds', async ({ page }) => {
  await page.setViewportSize({ width: 260, height: 220 })
  await page.goto('/')
  const welcome = page.getByRole('dialog', { name: 'Welcome', exact: true })
  await expect(welcome).toHaveCSS('width', '260px')
  await page.setViewportSize({ width: 1024, height: 768 })
  await expect.poll(async () => (await welcome.boundingBox())!.width).toBe(640)
  await expect.poll(async () => (await welcome.boundingBox())!.height).toBe(540)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.setViewportSize({ width: 844, height: 390 })
  await expect.poll(async () => { const box = (await welcome.boundingBox())!; return box.y + box.height }).toBeLessThanOrEqual(346)
})

