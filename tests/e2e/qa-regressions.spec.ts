test('unsaved Notepad close prompts and reset can be cancelled', async ({ page }) => {
  await client(page)
  await page.getByRole('button', { name: 'Reset incident', exact: true }).click()
  await page.getByRole('alertdialog', { name: 'Reset incident?' }).getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enter Simulation', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  await page.getByRole('navigation', { name: 'Start menu' }).getByRole('button', { name: /Notepad/ }).click()
  const note = page.getByRole('dialog', { name: 'Notepad', exact: true })
  await note.getByRole('textbox', { name: 'Notepad document' }).fill('Keep this draft')
  await page.getByRole('button', { name: 'Close Notepad', exact: true }).click()
  const prompt = page.getByRole('alertdialog', { name: 'Save changes to Notes.txt?' })
  await prompt.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(note.getByRole('textbox')).toHaveValue('Keep this draft')
  await page.getByRole('button', { name: 'Close Notepad', exact: true }).click()
  await prompt.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(note).toHaveCount(0)
})

